package dev.fractalbuildings.core.settlement;

import dev.fractalbuildings.core.check.Invariants;
import dev.fractalbuildings.core.check.SettlementChecks;
import dev.fractalbuildings.core.gen.GenRequest;
import dev.fractalbuildings.core.gen.v1.GeneratorV1;
import dev.fractalbuildings.core.ir.Box;
import dev.fractalbuildings.core.ir.Box3;
import dev.fractalbuildings.core.ir.BuildingIr;
import dev.fractalbuildings.core.ir.Layer;
import dev.fractalbuildings.core.ir.Lot;
import dev.fractalbuildings.core.ir.PlacedBuilding;
import dev.fractalbuildings.core.ir.Role;
import dev.fractalbuildings.core.ir.SceneDoc;
import dev.fractalbuildings.core.ir.TerrainPatch;
import dev.fractalbuildings.core.ir.Violation;
import dev.fractalbuildings.core.probe.BiomeProbe;
import dev.fractalbuildings.core.probe.TerrainProbe;
import dev.fractalbuildings.core.terrain.Grading;
import dev.fractalbuildings.core.terrain.GroundBox;
import dev.fractalbuildings.core.terrain.LatticePath;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * The voxel scene of one district tile (Phase 5, 5.7 mapping; docs/plans/phase5.md "DB"): every {@code build} lot of a
 * filled plan generated by generator v1 with its {@link dev.fractalbuildings.core.gen.Brief}, one {@link SceneDoc} with a
 * terrain patch over the tile plus {@value #MARGIN} blocks (with water) and the {@code ground} boxes of the street and
 * plaza grading, then {@link Invariants#check} on the scene and the settlement rules on the plan. A pure function of
 * the plan and the probes: the same plan gives the same scene in any order.
 *
 * <p>A lot the generator refuses (it throws {@code IllegalArgumentException} for lots too small or too steep, and
 * {@link Briefs#fill} should have screened those) falls back deterministically to a plain 1 to 2 storey house with
 * the same style, and if that is refused too the lot is left empty ({@code empty:gen-failed}); the returned plan
 * records both changes, so plan and scene always agree.
 */
public final class DistrictScenes {
	private DistrictScenes() {}

	public static final int MARGIN = 8;

	/**
	 * @param scene the scene
	 * @param plan the input plan with fallbacks applied to its lots and its {@code violations} filled with the
	 *     settlement rules (the scene has the building rules)
	 * @param fallbacks lot ids whose type was replaced or that were emptied
	 */
	public record Built(SceneDoc scene, DistrictPlan plan, List<String> fallbacks) {}

	/**
	 * @param exterior drop interior boxes, rooms and hooks from the buildings (a lighter scene for plan and street
	 *     views); the building invariants still run
	 */
	public static Built build(DistrictPlan plan, List<Landmark> landmarks, TerrainProbe exact, BiomeProbe biome, boolean exterior) {
		Rect t = plan.district().rect();
		TerrainPatch patch = TerrainPatch.sampleWithWater(exact, t.x() - MARGIN, t.z() - MARGIN, t.w() + 2 * MARGIN, t.d() + 2 * MARGIN);
		GeneratorV1 gen = new GeneratorV1();
		List<Lot> lots = new ArrayList<>();
		List<PlacedBuilding> buildings = new ArrayList<>();
		List<LotBrief> newLots = new ArrayList<>();
		List<String> fallbacks = new ArrayList<>();
		for (LotBrief l : plan.lots()) {
			if (!l.builds()) { newLots.add(l); continue; }
			Lot lot = new Lot(l.id(), l.x(), l.z(), l.w(), l.d(), l.front());
			LotBrief used = l;
			SceneDoc one = tryGenerate(gen, plan, used, lot, exact, biome);
			if (one == null) {
				fallbacks.add(l.id());
				if (!l.type().equals("house")) {
					used = new LotBrief(l.id(), l.x(), l.z(), l.w(), l.d(), l.front(), "house", l.style(), 1, 2, l.streets(), l.airRights(), l.frontY(), l.density(), LotBrief.BUILD);
					one = tryGenerate(gen, plan, used, lot, exact, biome);
				}
				if (one == null) {
					newLots.add(new LotBrief(l.id(), l.x(), l.z(), l.w(), l.d(), l.front(), l.type(), l.style(), l.minStoreys(), l.maxStoreys(), l.streets(), l.airRights(), l.frontY(), l.density(), "empty:gen-failed"));
					continue;
				}
			}
			PlacedBuilding b = one.buildings().get(0);
			lots.add(lot);
			buildings.add(new PlacedBuilding("b" + buildings.size(), b.lots(), b.ox(), b.oy(), b.oz(), b.rotation(), b.shell(), b.siteBoxes()));
			newLots.add(used);
		}
		List<Violation> settlement = new ArrayList<>();
		List<Box> ground = new ArrayList<>();
		for (Street s : plan.streets()) {
			List<LatticePath.Pt> pts = new ArrayList<>();
			for (Pt p : s.points()) pts.add(new LatticePath.Pt(p.x(), p.z()));
			Grading.RoadGrade g = Grading.road(pts, s.width(), exact);
			addBoxes(g.boxes(), ground);
			settlement.addAll(SettlementChecks.roadGrade(s.id(), g.profile().x(), g.profile().z(), g.profile().y()));
		}
		for (Plaza p : plan.plazas()) {
			Optional<Grading.PlazaGrade> g = Grading.plaza(new dev.fractalbuildings.core.terrain.Rect(p.x(), p.z(), p.w(), p.d()), exact);
			if (g.isPresent()) addBoxes(g.get().boxes(), ground);
			else settlement.add(new Violation("plaza-grade", null, "plaza " + p.id() + " cannot be graded (too rough or wet)", List.of(new Box3(p.x(), p.y() - 1, p.z(), p.w(), 1, p.d()))));
		}
		DistrictPlan filled = new DistrictPlan(plan.genVersion(), plan.seed(), plan.district(), plan.streets(), plan.plazas(), newLots, plan.scene(), List.of());
		settlement.addAll(SettlementChecks.district(filled, landmarks));
		DistrictPlan out = new DistrictPlan(plan.genVersion(), plan.seed(), plan.district(), plan.streets(), plan.plazas(), newLots, plan.scene(), settlement);
		SceneDoc draft = new SceneDoc(GeneratorV1.GEN_VERSION, plan.seed(), patch, lots, buildings, ground, List.of());
		List<Violation> found = Invariants.check(draft, exact); // on the full buildings, then stripped
		if (exterior) {
			List<PlacedBuilding> stripped = new ArrayList<>();
			for (PlacedBuilding b : buildings) stripped.add(new PlacedBuilding(b.id(), b.lots(), b.ox(), b.oy(), b.oz(), b.rotation(), exterior(b.shell()), b.siteBoxes()));
			buildings = stripped;
		}
		SceneDoc scene = new SceneDoc(GeneratorV1.GEN_VERSION, plan.seed(), patch, lots, buildings, ground, found);
		return new Built(scene, out, fallbacks);
	}

	private static SceneDoc tryGenerate(GeneratorV1 gen, DistrictPlan plan, LotBrief l, Lot lot, TerrainProbe exact, BiomeProbe biome) {
		try {
			return gen.generate(new GenRequest(plan.seed(), lot, l.type(), l.style(), exact, biome, l.brief()));
		} catch (IllegalArgumentException e) {
			return null;
		}
	}

	/** The same shell without interiors: no interior-layer boxes, rooms, hooks or room-to-room openings (an opening names rooms). */
	static BuildingIr exterior(BuildingIr s) {
		List<Box> boxes = new ArrayList<>();
		for (Box b : s.boxes()) if (b.layer() != Layer.INTERIOR) boxes.add(b);
		return new BuildingIr(s.spec(), s.bounds(), s.storeys(), s.volumes(), List.of(), List.of(), s.roofs(), boxes, List.of());
	}

	/** Maps TA's ground box kinds to roles: road and plaza surfaces, cuts are air, everything else (fill, deck, pier) is ground. */
	static Role role(GroundBox.Kind k) {
		return switch (k) {
			case ROAD -> Role.ROAD;
			case PLAZA -> Role.PAVING;
			case CUT -> Role.AIR;
			case FILL, DECK, PIER -> Role.GROUND;
		};
	}

	private static void addBoxes(List<GroundBox> boxes, List<Box> out) {
		for (GroundBox g : boxes) out.add(new Box(g.box(), role(g.kind()), Layer.GROUND, Box.NO_STOREY));
	}
}
