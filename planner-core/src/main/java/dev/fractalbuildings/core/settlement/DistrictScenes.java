/**
 * The voxel scene of one district tile (Phase 5, 5.7 mapping; docs/plans/phase5.md "DB"): every {@code build} lot of a
 * filled plan generated by generator v1 with its {@link dev.fractalbuildings.core.gen.Brief}, one {@link SceneDoc} with a
 * terrain patch over the tile plus {@value #MARGIN} blocks (with water) and the {@code ground} boxes of the street and
 * plaza grading, then {@link Invariants#check} on the scene and the settlement rules on the plan. A pure function of
 * the plan and the probes: the same plan gives the same scene in any order.
 *
 * <p>A lot the generator refuses (it throws {@code IllegalArgumentException} for lots too small or too steep, and
 * {@link Briefs#fill} should have screened those) falls back deterministically to a plain 1 to 2 storey house with
 * the same style, and if that is refused too the lot is left empty ({@code empty:gen-failed}); the returned plan
 * records both changes, so plan and scene always agree.
 */
public final class DistrictScenes {
	private DistrictScenes() {}

	public static final int MARGIN = 8;

	/**
	 * @param scene the scene
	 * @param plan the input plan with fallbacks applied to its lots and its {@code violations} filled with the
	 *     settlement rules (the scene has the building rules)
	 * @param fallbacks lot ids whose type was replaced or that were emptied
	 */
	public record Built(SceneDoc scene, DistrictPlan plan, List<String> fallbacks, List<Violation> warnings) {
		/** Without design warnings. */
		public Built(SceneDoc scene, DistrictPlan plan, List<String> fallbacks) { this(scene, plan, fallbacks, List.of()); }
	}

	/**
	 * @param exterior drop interior boxes, rooms and hooks from the buildings (a lighter scene for plan and street
	 *     views); the building invariants still run
	 */
	public static Built build(DistrictPlan plan, List<Landmark> landmarks, TerrainProbe exact, BiomeProbe biome, boolean exterior) {
		return build(plan, landmarks, exact, biome, exterior, DEFAULT_TIER);
	}

	/** As above, for a settlement of {@code tier}: the tier picks the street surfaces ({@link #roadRole}). */
	public static Built build(DistrictPlan plan, List<Landmark> landmarks, TerrainProbe exact, BiomeProbe biome, boolean exterior, Tier tier) {
		Rect t = plan.district().rect();
		TerrainPatch patch = TerrainPatch.sampleWithWater(exact, t.x() - MARGIN, t.z() - MARGIN, t.w() + 2 * MARGIN, t.d() + 2 * MARGIN);
		Lots gen = generateLots(plan, exact, biome);
		List<Lot> lots = new ArrayList<>();
		List<PlacedBuilding> buildings = new ArrayList<>();
		for (Generated g : gen.generated()) {
			lots.add(g.lot());
			buildings.add(g.building());
		}
		List<LotBrief> newLots = gen.lots();
		List<String> fallbacks = gen.fallbacks();
		Ground g = ground(plan, exact, tier);
		List<Violation> settlement = new ArrayList<>(g.settlement());
		List<Box> ground = g.boxes();
		DistrictPlan filled = new DistrictPlan(plan.genVersion(), plan.seed(), plan.district(), plan.streets(), plan.plazas(), newLots, plan.scene(), List.of());
		settlement.addAll(SettlementChecks.district(filled, landmarks));
		DistrictPlan out = new DistrictPlan(plan.genVersion(), plan.seed(), plan.district(), plan.streets(), plan.plazas(), newLots, plan.scene(), settlement);
		SceneDoc draft = new SceneDoc(GeneratorV1.GEN_VERSION, plan.seed(), patch, lots, buildings, ground, List.of());
		List<Violation> found = Invariants.check(draft, exact); // on the full buildings, then stripped
		List<Violation> warnings = dev.fractalbuildings.core.check.DoorChecks.warnings(draft, exact); // DS-45 design warnings (door-rise beyond the planner's limit, flight-landings), also on the full buildings
		if (exterior) {
			List<PlacedBuilding> stripped = new ArrayList<>();
			for (PlacedBuilding b : buildings) stripped.add(new PlacedBuilding(b.id(), b.lots(), b.ox(), b.oy(), b.oz(), b.rotation(), exterior(b.shell()), b.siteBoxes()));
			buildings = stripped;
		}
		SceneDoc scene = new SceneDoc(GeneratorV1.GEN_VERSION, plan.seed(), patch, lots, buildings, ground, found);
		return new Built(scene, out, fallbacks, warnings);
	}

	/**
	 * One generated lot.
	 *
	 * @param index the lot's index in the input plan's {@code lots}
	 * @param brief the brief actually used (the house fallback's when the type was replaced)
	 * @param lot the generated scene's lot: carries airRights and frontY when the building jetties over the street
	 * @param building the placed building, id {@code b<n>} with {@code n} counting generated buildings in lot order
	 */
	public record Generated(int index, LotBrief brief, Lot lot, PlacedBuilding building) {}

	/**
	 * @param generated the buildings, in lot order
	 * @param lots the plan's lots with fallbacks applied (same order and count as the input)
	 * @param fallbacks lot ids whose type was replaced or that were emptied
	 */
	public record Lots(List<Generated> generated, List<LotBrief> lots, List<String> fallbacks) {}

	/**
	 * Generates every {@code build} lot of a filled plan with generator v1 (see {@link #generateLot}). A pure function of the plan and
	 * the probes; each lot depends on its own brief alone.
	 */
	public static Lots generateLots(DistrictPlan plan, TerrainProbe exactIn, BiomeProbe biome) {
		TerrainProbe exact = new dev.fractalbuildings.core.probe.MemoProbe(exactIn); // DISTPERF: the door retries and checks read the same columns many times; one thread, one district
		List<Generated> out = new ArrayList<>();
		List<LotBrief> newLots = new ArrayList<>();
		List<String> fallbacks = new ArrayList<>();
		for (int i = 0; i < plan.lots().size(); i++) {
			LotBrief l = plan.lots().get(i);
			if (!l.builds()) { newLots.add(l); continue; }
			Generated g = generateLot(plan.seed(), i, l, out.size(), Briefs.withStreetFront(plan, l, exact), biome);
			if (g == null) {
				fallbacks.add(l.id());
				newLots.add(new LotBrief(l.id(), l.x(), l.z(), l.w(), l.d(), l.front(), l.type(), l.style(), l.minStoreys(), l.maxStoreys(), l.streets(), l.airRights(), l.frontY(), l.density(), "empty:gen-failed", l.walk()));
				continue;
			}
			if (g.brief().builds() && dev.fractalbuildings.core.check.DoorChecks.bankDoor(g.lot(), g.building(), Briefs.withStreetFront(plan, l, exact))) { // DOORBANK: a front door below the street with no way up to it
				fallbacks.add(l.id());
				newLots.add(new LotBrief(l.id(), l.x(), l.z(), l.w(), l.d(), l.front(), l.type(), l.style(), l.minStoreys(), l.maxStoreys(), l.streets(), l.airRights(), l.frontY(), l.density(), "empty:bank", l.walk()));
				continue;
			}
			if (!g.brief().equals(l)) fallbacks.add(l.id());
			out.add(g);
			newLots.add(g.brief());
		}
		return new Lots(out, newLots, fallbacks);
	}

	/**
	 * One {@code build} lot with its fallback rule: a lot the generator refuses (it throws {@code IllegalArgumentException}) is
	 * generated as a 1 to 2 storey house of the same style instead (not a wall-ring lot, not a lot that already is a house); null
	 * when that is refused too. {@code index} is the lot's index in its plan, {@code n} numbers the building ({@code b<n>}).
	 */
	public static Generated generateLot(long seed, int index, LotBrief l, int n, TerrainProbe exact, BiomeProbe biome) {
		GeneratorV1 gen = new GeneratorV1();
		Lot lot = new Lot(l.id(), l.x(), l.z(), l.w(), l.d(), l.front());
		LotBrief used = l;
		SceneDoc one = tryGenerate(gen, seed, used, lot, exact, biome);
		if (one == null && !l.type().equals("house") && !dev.fractalbuildings.core.settlement.tiers.WallRing.isRingLotId(l.id())) {
			used = new LotBrief(l.id(), l.x(), l.z(), l.w(), l.d(), l.front(), "house", l.style(), 1, 2, l.streets(), l.airRights(), l.frontY(), l.density(), LotBrief.BUILD);
			one = tryGenerate(gen, seed, used, lot, exact, biome);
		}
		if (one == null) return null;
		PlacedBuilding b = one.buildings().get(0);
		return new Generated(index, used, one.lots().get(0), new PlacedBuilding("b" + n, b.lots(), b.ox(), b.oy(), b.oz(), b.rotation(), b.shell(), b.siteBoxes()));
	}

	/**
	 * @param boxes the world-frame ground boxes of every street and plaza, in plan order
	 * @param settlement the road-grade and plaza-grade violations found on the way
	 */
	public record Ground(List<Box> boxes, List<Violation> settlement) {}

	/** The ground boxes of the plan's streets and plazas ({@link Grading}), with the grade violations. */
	public static Ground ground(DistrictPlan plan, TerrainProbe exact) { return ground(plan, exact, DEFAULT_TIER); }

	/** The tier a plan is built as when the caller does not say (village: dirt or gravel tracks). */
	public static final Tier DEFAULT_TIER = Tier.VILLAGE;

	/**
	 * The street surface role of a road kind in a settlement of {@code tier} (DS-30, ROADMAP 7.10): tracks below town, stone streets in a town,
	 * and in a city or metropolis cobbled deepslate for arterials and main streets, light grey concrete for streets and lanes. A path is always a
	 * track; a quay is paving. One role per street, so a road changes material only where it meets another kind.
	 */
	public static Role roadRole(Tier tier, RoadKind kind) {
		if (kind == RoadKind.QUAY) return Role.PAVING;
		if (kind == RoadKind.PATH || tier.compareTo(Tier.TOWN) < 0) return Role.ROAD;
		if (tier == Tier.TOWN) return Role.ROAD_TOWN;
		return kind == RoadKind.ARTERIAL || kind == RoadKind.MAIN ? Role.ROAD_MAIN : Role.ROAD_CITY;
	}

	/** The ground boxes of the plan's streets and plazas for a settlement of {@code tier}. */
	public static Ground ground(DistrictPlan plan, TerrainProbe exact, Tier tier) {
		List<Violation> settlement = new ArrayList<>();
		List<Box> ground = new ArrayList<>();
		// pieces of one whole street (a road cut by a square into "r", "r.1"): a cell two of them cover is built by the first, as the whole
		// street would build it, so a later piece's first column does not lay a second surface there at its own level (JUNCTION)
		java.util.TreeMap<String, Integer> pieces = new java.util.TreeMap<>();
		for (Street s : plan.streets()) pieces.merge(SettlementChecks.wholeStreet(s.id()), 1, Integer::sum);
		java.util.TreeMap<String, java.util.TreeSet<Long>> built = new java.util.TreeMap<>();
		for (Street s : plan.streets()) {
			List<LatticePath.Pt> pts = new ArrayList<>();
			for (Pt p : s.points()) pts.add(new LatticePath.Pt(p.x(), p.z()));
			String whole = SettlementChecks.wholeStreet(s.id());
			java.util.TreeSet<Long> done = pieces.get(whole) > 1 ? built.computeIfAbsent(whole, k -> new java.util.TreeSet<>()) : null;
			Grading.RoadGrade g = Grading.road(pts, s.y(), s.width(), exact, done == null ? null : (x, z) -> done.contains(((long) z << 32) ^ (x & 0xffffffffL))); // the plan's heights, so both tiles at a border build the same road
			if (done != null) {
				int h = s.width() / 2;
				for (int i = 0; i < g.profile().size(); i++) {
					for (int dz = 0; dz < s.width(); dz++) for (int dx = 0; dx < s.width(); dx++) done.add(((long) (g.profile().z()[i] - h + dz) << 32) ^ ((g.profile().x()[i] - h + dx) & 0xffffffffL));
				}
			}
			addBoxes(g.boxes(), ground, roadRole(tier, s.kind()), tier.atLeast(Tier.CITY)); // DS-44: city decks carry the street surface; piers stay deck
			settlement.addAll(SettlementChecks.roadGrade(s.id(), g.profile().x(), g.profile().z(), g.profile().y()));
		}
		for (Plaza p : plan.plazas()) {
			Optional<Grading.PlazaGrade> g = Grading.plaza(new Rect(p.x(), p.z(), p.w(), p.d()), exact);
			if (g.isPresent()) addBoxes(g.get().boxes(), ground, Role.ROAD, false);
			else settlement.add(new Violation("plaza-grade", null, "plaza " + p.id() + " cannot be graded (too rough or wet)", List.of(new Box3(p.x(), p.y() - 1, p.z(), p.w(), 1, p.d()))));
		}
		// Boxes apply in list order and a later one wins. Surfaces go last, so one street's air (headroom, cut) or earth can never remove the
		// surface or earth of another street that crosses it at a different level: air first, then earth (so a street's earth under its surface is never
		// cut away by another street's trench), then bridge parts, then road and plaza surfaces.
		ground.sort(java.util.Comparator.comparingInt(b -> phase(b.role())));
		return new Ground(ground, settlement);
	}

	private static int phase(Role r) {
		return switch (r) {
			case AIR -> 0;
			case GROUND -> 1;
			case DECK -> 2;
			default -> 3;
		};
	}

	private static SceneDoc tryGenerate(GeneratorV1 gen, long seed, LotBrief l, Lot lot, TerrainProbe exact, BiomeProbe biome) {
		try {
			return gen.generate(new GenRequest(seed, lot, l.type(), l.style(), exact, biome, l.brief()));
		} catch (IllegalArgumentException e) {
			return null;
		}
	}

	/** The same shell without interiors: no interior-layer boxes, rooms, hooks or room-to-room openings (an opening names rooms). */
	static BuildingIr exterior(BuildingIr s) {
		List<Box> boxes = new ArrayList<>();
		for (Box b : s.boxes()) if (b.layer() != Layer.INTERIOR) boxes.add(b);
		return new BuildingIr(s.spec(), s.bounds(), s.storeys(), s.volumes(), List.of(), List.of(), s.roofs(), boxes, List.of());
	}

	/** Maps TA's ground box kinds to roles: road and plaza surfaces, cuts are air, fill is ground, bridge decks and piers are deck. */
	static Role role(GroundBox.Kind k) { return k.role(); }

	/** The role of a ground box: road surfaces take {@code surface}; so does a bridge deck (not a pier) when {@code deckIsRoad} (DS-44, city and metropolis). */
	static Role boxRole(GroundBox.Kind k, Role surface, boolean deckIsRoad) { return k == GroundBox.Kind.ROAD || (deckIsRoad && k == GroundBox.Kind.DECK) ? surface : role(k); }

	/** @param surface the role of the road surface of these boxes (paving for a quay, else by tier and kind). */
	private static void addBoxes(List<GroundBox> boxes, List<Box> out, Role surface, boolean deckIsRoad) {
		for (GroundBox g : boxes) {
			Role r = boxRole(g.kind(), surface, deckIsRoad);
			out.add(new Box(g.box(), r, Layer.GROUND, Box.NO_STOREY));
		}
	}
}
