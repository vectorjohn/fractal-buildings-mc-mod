#!/usr/bin/env bash
# Self-test for scripts/status.sh (W6): stub sources in a temp state dir, fake transcripts, a missing and
# a hanging source; then a smoke run with the real helper scripts on an empty temp state.
#   scripts/status-selftest.sh      exit 0 all pass, 1 a check failed
set -uo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
ST="$HERE/status.sh"
T=$(mktemp -d "${TMPDIR:-/tmp}/status-selftest.XXXXXX")
trap 'rm -rf "$T"' EXIT
fail=0
ok()  { echo "ok   $1"; }
bad() { echo "FAIL $1"; fail=1; }
has()   { if grep -qF -- "$2" "$3"; then ok "$1"; else bad "$1 (no '$2' in $3)"; sed 's/^/     | /' "$3" | head -n 80; fi; }
hasnt() { if grep -qF -- "$2" "$3"; then bad "$1 ('$2' in $3)"; else ok "$1"; fi; }

S="$T/scripts"; STATE="$T/state"; TR="$T/transcripts"
mkdir -p "$S" "$STATE/board" "$STATE/status" "$STATE/worktrees/wt1/build/remote" "$TR/sess/subagents"

# --- stub sources ---------------------------------------------------------------------------------
cat > "$S/board.sh" <<'EOF'
#!/usr/bin/env bash
[[ $1 == batch ]] && echo "HEAVY BATCH DUE: heavy batch: 4 of 4 in-world merge(s) on claude/run-x"
EOF
cat > "$S/needs-user.sh" <<'EOF'
#!/usr/bin/env bash
exit 0
EOF
cat > "$S/locks.sh" <<'EOF'
#!/usr/bin/env bash
printf '%-32s %s\n' heavy.lock "held: pid 42 since 2026-11-05 10:00:00: client-test" merge.lock free postmerge.lock free
echo "    waiter: pid 43 since 2026-11-05 10:01:00: test-all"
EOF
cat > "$S/anywhere.sh" <<'EOF'
#!/usr/bin/env bash
exec sleep 30
EOF
cat > "$S/tested.sh" <<'EOF'
#!/usr/bin/env bash
echo "time  tree  layer"
EOF
chmod +x "$S"/*.sh   # postmerge-status.sh deliberately missing
printf '# time\ttree\tlayer\texit\thost\trenderer\tcommit\tlabel\tevidence\tcommand\n2026-11-05T10:00:00Z\tabcdef1234567\tfast\t0\tlocal\t-\tdeadbeef\tmy-item\t/x\tscripts/test-all.sh --no-client\n' > "$STATE/tested.tsv"

printf '# slug\tlane\tsince\tagent\tbranch\thost\tnote\tadded\n' > "$STATE/board/items.tsv"
printf 'alpha\tcoding\t2026-11-05T10:00:00Z\tcoder-1\tclaude/alpha\t\tdoing a|b\t2026-11-05T09:00:00Z\n' >> "$STATE/board/items.tsv"
printf 'beta\tverify\t2026-11-05T11:00:00Z\tverifier\tclaude/beta\tperf1\t\t2026-11-05T09:00:00Z\n' >> "$STATE/board/items.tsv"
printf 'gamma\tdone\t2026-11-05T11:00:00Z\t\t\t\t\t2026-11-05T09:00:00Z\n' >> "$STATE/board/items.tsv"

cat > "$STATE/status/needs-user.md" <<'EOF'
# Needs the user

Generated by `scripts/needs-user.sh` at 2026-11-05T12:00:00Z (run branch `claude/run-x`).

# Asks

- [ ] BLOCKING **ask-1** (2026-11-05T11:00, coder): allow the thing
- [ ] **ask-2** (2026-11-05T11:05, coder): minor thing

# Permission denials

- 2026-11-05T10:00 coder x, **[R]**, id abc: Bash `y`

# Open questions

3 open in [QUESTIONS.md](docs/QUESTIONS.md) (answer there, `-- @John ...`):
EOF

# watchdog page and bg.sh jobs (the real bg.sh, on the temp state's jobs dir)
cat > "$STATE/status/watchdog.md" <<'EOF'
# Watchdog

Generated by `scripts/watchdog.sh` at 2026-11-05T12:00:00Z on host.

# Needs action (1)

- stall: heavy.lock held 3h by pid 42 (`scripts/locks.sh list`)

# Notes (2)

- quiet: agent x
- worktree: y merged
EOF
touch -d "-20 minutes" "$STATE/status/watchdog.md"
cp "$HERE/bg.sh" "$S/bg.sh"; mkdir -p "$S/lib"; cp "$HERE/lib/procs.sh" "$S/lib/"
J="$STATE/status/jobs"; mkdir -p "$J"
recent=$(date -u -d '-1 hour' +%FT%TZ)
printf 'status=PASS\nrc=0\npid=1\nlabel=fresh-pass\nstart=%s\ncmd=scripts/test-all.sh --no-client\n' "$recent" > "$J/fresh-pass.state"
printf 'status=FAIL\nrc=1\npid=1\nlabel=old-fail\nstart=2020-01-01T00:00:00Z\ncmd=scripts/old.sh\n' > "$J/old-fail.state"
printf 'status=RUNNING\nrc=\npid=999999999\nlabel=ghost\nstart=%s\ncmd=scripts/ghost.sh\n' "$recent" > "$J/ghost.state"

printf 'job=j1\nworker=perf1\nworktree=/x/worktrees/wt1\ncmd=scripts/client-test.sh\nstarted_at=2026-11-05 10:00:00 -0800\nstatus=running\n' > "$STATE/worktrees/wt1/build/remote/j1.state"
printf 'job=j0\nworker=perf1\nworktree=/x/worktrees/wt1\ncmd=scripts/old.sh\nstatus=fetched\n' > "$STATE/worktrees/wt1/build/remote/j0.state"

# --- fake transcripts -----------------------------------------------------------------------------
A="$TR/sess/subagents"
tu() { printf '{"type":"assistant","message":{"content":[{"type":"tool_use","id":"t%s","name":"Bash","input":{"command":"cd /r/.claude/worktrees/%s && make %s"}}]}}\n' "$1" "$2" "$3"; }
tr_() { printf '{"type":"user","message":{"content":[{"type":"tool_result","tool_use_id":"t%s"}]},"toolUseResult":{"message":"%s"},"cwd":"/r/.claude/worktrees/run-x"}\n' "$1" "$2"; }
{ tu 1 wt-run running; } > "$A/agent-run1.jsonl"
echo '{"agentType":"coder","description":"RUNNER: does work"}' > "$A/agent-run1.meta.json"
{ tu 1 wt-done x; tr_ 1 "Report delivered to your caller."; } > "$A/agent-done1.jsonl"
echo '{"agentType":"assistant","description":"DONER: finished"}' > "$A/agent-done1.meta.json"
{ tu 1 wt-txt x; tr_ 1 ok; printf '{"type":"assistant","message":{"content":[{"type":"text","text":"bye"}]}}\n'; } > "$A/agent-text1.jsonl"
echo '{"agentType":"assistant","description":"TEXTER: ended"}' > "$A/agent-text1.meta.json"
touch -d '-10 minutes' "$A/agent-text1.jsonl"
{ tu 1 wt-wait sleepy; tr_ 1 ok; } > "$A/agent-wait1.jsonl"
echo '{"agentType":"assistant","description":"WAITER: on a job"}' > "$A/agent-wait1.meta.json"
touch -d '-20 minutes' "$A/agent-wait1.jsonl"
{ tu 1 wt-old x; } > "$A/agent-old1.jsonl"; touch -d '-5 hours' "$A/agent-old1.jsonl"
{ printf '{"type":"mode"}\n'; } > "$TR/sess.jsonl"

export FB_STATE_DIR="$STATE" FB_STATUS_SCRIPTS="$S" FB_TRANSCRIPTS="$TR" FB_STATUS_TIMEOUT=2 FB_RUN_BRANCH=claude/run-x
OUT="$T/out.txt" B="$STATE/status/board.md"
t0=$(date +%s)
"$ST" > "$OUT" 2>&1; rc=$?
t1=$(date +%s)
[[ $rc == 0 ]] && ok "exit 0 with a missing and a hanging source" || bad "exit $rc"
(( t1 - t0 < 15 )) && ok "finished in $((t1 - t0)) s" || bad "took $((t1 - t0)) s"
[[ -s $B ]] && ok "board.md written" || bad "no board.md"
cmp -s "$OUT" "$B" && ok "printed page = board.md" || bad "printed output differs from board.md"
has  "needs-user counts"         "Open asks: **2**; permission denials: **1**; open questions: **3**" "$B"
has  "blocking ask in full"      "BLOCKING **ask-1**" "$B"
hasnt "non-blocking ask hidden when a blocking one exists" "ask-2" "$B"
has  "heavy batch line"          "HEAVY BATCH DUE" "$B"
has  "lane row"                  "| coding | alpha |" "$B"
has  "pipe in note escaped"      'doing a\|b' "$B"
has  "verify row with host"      "| verify | beta |" "$B"
hasnt "done items left out"      "| gamma |" "$B"
has  "in-flight count"           "2 in flight, 1 done" "$B"
has  "running agent"             "RUNNER: does work" "$B"
has  "agent worktree from tool input, not cwd" "| wt-run |" "$B"
has  "last tool, cd stripped"    '`Bash make running`' "$B"
has  "waiting agent is quiet"    "| quiet | 20m | assistant: WAITER" "$B"
hasnt "handed-back agent hidden" "DONER" "$B"
hasnt "text-ended agent hidden"  "TEXTER" "$B"
hasnt "old transcript out of window" "wt-old" "$B"
has  "session listed"            "| session |" "$B"
has  "held lock"                 "heavy.lock" "$B"
has  "lock waiter"               "waiter: pid 43" "$B"
has  "free locks counted"        "2 other lock(s) free" "$B"
has  "hanging source times out"  "\`anywhere.sh\` took over 2s" "$B"
has  "remote job not fetched"    "| perf1 | running |" "$B"
hasnt "fetched remote job hidden" "old.sh" "$B"
has  "missing source degrades"   "\`postmerge-status.sh\` not found" "$B"
has  "test ledger row"           "| fast | 0 | local | my-item |" "$B"
has  "watchdog counts"           "Needs action: **1**; notes: **2**" "$B"
has  "watchdog act line in full" "- stall: heavy.lock held 3h by pid 42" "$B"
hasnt "watchdog notes not listed" "worktree: y merged" "$B"
has  "watchdog page stale"       "**Stale**" "$B"
has  "bg job recent"             "| PASS | fresh-pass | 0 | 1h ago | \`scripts/test-all.sh --no-client\` |" "$B"
has  "bg job runner gone: DIED"  "| DIED | ghost | - |" "$B"
hasnt "bg job older than 24 h"   "old-fail" "$B"
has  "bg jobs on record"         "3 on record" "$B"
grep -q '^status=DIED$' "$J/ghost.state" && ok "bg.sh marked the ghost DIED" || bad "ghost not marked DIED"
[[ ! -e "$T/docs/STATUS.md" ]] && ok "nothing published without --publish" || bad "STATUS.md written without --publish"

# lock ages: a suite slot note in local time (no zone) 21 min old, on a host 8 h behind UTC, reads 21m, not 8h
mv "$S/locks.sh" "$T/locks.sh.keep"
cat > "$S/locks.sh" <<EOF
#!/usr/bin/env bash
printf '%-32s %s\n' suite.lock.1 "held: pid 44 since $(TZ=XST8 date -d '-21 min' '+%F %T'): anywhere: test-all" heavy.lock free
EOF
chmod +x "$S/locks.sh"
TZ=XST8 "$ST" --skip machines,agents --quiet > "$OUT" 2>&1
has "suite slot age in local time" "held: pid 44 for 21m (since " "$B"
has "suite slot time keeps its zone" " XST): anywhere: test-all" "$B"
mv "$T/locks.sh.keep" "$S/locks.sh"

# --publish (W12): STATUS.md in the docs space only while git ignores it there
DOCS="$T/docs"; git init -q "$DOCS"
export FB_STATUS_PAGE_DIR="$DOCS"
P="$DOCS/STATUS.md"
"$ST" --skip machines,agents --quiet --publish > "$OUT" 2>&1; rc=$?
[[ $rc == 3 ]] && ok "publish refused while STATUS.md is not ignored (exit 3)" || bad "not-ignored publish: exit $rc"
[[ ! -e $P ]] && ok "nothing written where it is not ignored" || bad "STATUS.md written although not ignored"
grep -q "does not ignore STATUS.md" "$OUT" && ok "says why" || bad "no reason printed: $(cat "$OUT")"
[[ -s $B ]] && ok "board.md still written" || bad "board.md missing after refused publish"
# STATUS.md ignored but not STATUS/: the page alone, links into .claude/ as plain paths, exit 3
printf '/STATUS.md\n' > "$DOCS/.gitignore"
"$ST" --skip machines,agents --quiet --publish > "$OUT" 2>&1; rc=$?
[[ $rc == 3 && -s $P ]] && ok "STATUS.md published once ignored, STATUS/ refused (exit 3)" || bad "publish without /STATUS/: exit $rc, $(cat "$OUT")"
grep -q "STATUS/ pages not published" "$OUT" && ok "says why the pages are missing" || bad "no reason for the missing pages: $(cat "$OUT")"
[[ ! -e "$DOCS/STATUS" ]] && ok "no STATUS/ where it is not ignored" || bad "STATUS/ written although not ignored"
has  "hidden link made a path"   '`.claude/status/needs-user.md`' "$P"
hasnt "no page links without pages" "](STATUS/" "$P"
# both ignored: the page and its STATUS/ copies
printf '/STATUS.md\n/STATUS/\n' > "$DOCS/.gitignore"
printf '2026-11-05T11:00:00Z act stall heavy.lock\n2026-11-05T11:05:00Z note quiet agent x\n' > "$STATE/status/watchdog.log"
printf '2026-11-05T11:00:00Z LEAVE pg-42 (bg x): its owner runs\n' > "$STATE/status/reap.log"
printf '# Board\n\nGenerated by `scripts/board.sh md`. Item codes: [GLOSSARY.md](docs/GLOSSARY.md).\n\n# Last moves\n\n- alpha ready -> coding\n' > "$STATE/status/lanes.md"
printf 'line one of fresh-pass\nBUILD SUCCESSFUL\n' > "$J/fresh-pass.log"
"$ST" --skip machines,agents --quiet --publish > "$OUT" 2>&1; rc=$?
[[ $rc == 0 && -s $P ]] && ok "published once both are ignored" || bad "publish: exit $rc, $(cat "$OUT")"
has  "page title"                "# Status" "$P"
hasnt "board title dropped"      "# Run status" "$P"
has  "page has the board"        "| coding | alpha |" "$P"
has  "page has the full needs-user list" "# Needs the user: full list" "$P"
has  "non-blocking ask on the page" "**ask-2**" "$P"
hasnt "no tasks on the page"     "- [ ]" "$P"
hasnt "no links into .claude/"   "](.claude/" "$P"
has  "needs-user link to its copy" "[needs-user.md](STATUS/needs-user.md)" "$P"
has  "watchdog link to its copy" "[watchdog.md](STATUS/watchdog.md)" "$P"
has  "lanes link to its copy"    "[lanes.md](STATUS/lanes.md)" "$P"
has  "list of the full pages"    "[background jobs](STATUS/jobs.md)" "$P"
has  "repo link kept"            "[QUESTIONS.md](docs/QUESTIONS.md)" "$P"
pages=(needs-user watchdog lanes jobs merge-queue reap)
miss=""; for p in "${pages[@]}"; do [[ -s "$DOCS/STATUS/$p.md" ]] || miss+=" $p"; done
[[ -z $miss ]] && ok "all ${#pages[@]} STATUS/ pages written" || bad "STATUS/ pages missing:$miss"
# every link into the published pages resolves to a file there (repo links like docs/ are not in this temp space)
bad_links=""
for f in "$P" "$DOCS"/STATUS/*.md; do
	d=$(dirname "$f")
	while IFS= read -r l; do
		case $l in *STATUS*|*.md) ;; *) continue ;; esac
		case $l in docs/*|../docs/*) continue ;; esac
		[[ -f "$d/$l" ]] || bad_links+=" ${f#"$DOCS"/}:$l"
	done < <(grep -o '\]([^)]*)' "$f" | sed 's/^](//; s/)$//' | grep -v '^[a-z]*:')
done
[[ -z $bad_links ]] && ok "links to the status pages resolve" || bad "dangling links:$bad_links"
for p in "${pages[@]}"; do grep -qF '[Status](../STATUS.md)' "$DOCS/STATUS/$p.md" || bad_links+=" $p"; done
[[ -z $bad_links ]] && ok "every copy links back to STATUS.md" || bad "no back link in:$bad_links"
has  "copy keeps its title"      "# Watchdog" "$DOCS/STATUS/watchdog.md"
has  "watchdog copy has the act line" "- stall: heavy.lock held <6h by pid 42" "$DOCS/STATUS/watchdog.md"
has  "watchdog copy has the log tail" "note quiet agent x" "$DOCS/STATUS/watchdog.md"
has  "needs-user copy: repo link one folder up" "[QUESTIONS.md](../docs/QUESTIONS.md)" "$DOCS/STATUS/needs-user.md"
hasnt "needs-user copy: no tasks" "- [ ]" "$DOCS/STATUS/needs-user.md"
has  "lanes copy: repo link one folder up" "[GLOSSARY.md](../docs/GLOSSARY.md)" "$DOCS/STATUS/lanes.md"
has  "jobs copy lists the jobs"  "fresh-pass" "$DOCS/STATUS/jobs.md"
has  "jobs copy has a log tail"  "BUILD SUCCESSFUL" "$DOCS/STATUS/jobs.md"
hasnt "jobs copy: no tail of an old job" "# old-fail" "$DOCS/STATUS/jobs.md"
has  "reap copy has the log tail" "LEAVE pg-42" "$DOCS/STATUS/reap.md"
has  "merge-queue copy degrades without its script" "\`merge-queue.sh\` not found" "$DOCS/STATUS/merge-queue.md"
for f in "$P" "$DOCS"/STATUS/*.md; do head -n1 "$f" | grep -q '^# ' || bad "no title line in $f"; done
[[ -z $(git -C "$DOCS" status --porcelain --ignored=no) || $(git -C "$DOCS" status --porcelain) == "?? .gitignore" ]] \
	&& ok "pages invisible to git status" || bad "git status shows: $(git -C "$DOCS" status --porcelain)"
ls -a "$DOCS" "$DOCS/STATUS" | grep -q "\.tmp" && bad "temp file left in the docs space" || ok "no temp file in the docs space"
has  "page ages are coarse"      "Last pass <1h ago" "$P"
hasnt "no minute ages on the page" "Last pass 20m ago" "$P"
# quiet when nothing changed: SilverBullet treats a new mtime as an edit
mt() { stat -c %Y "$P"; }
mts() { stat -c '%Y %n' "$DOCS"/STATUS/*.md; }
touch -d '-1 hour' "$P" "$DOCS"/STATUS/*.md; m0=$(mt); ms0=$(mts)
sleep 1   # so the generated-at second differs between the two runs
"$ST" --skip machines,agents --quiet --publish > "$OUT" 2>&1; rc=$?
[[ $rc == 0 && $(mt) == "$m0" ]] && ok "no change: STATUS.md left alone (same mtime)" || bad "no-change publish rewrote STATUS.md (rc $rc)"
[[ $(mts) == "$ms0" ]] && ok "no change: STATUS/ pages left alone (same mtimes)" || bad "no-change publish rewrote: $(diff <(echo "$ms0") <(mts) | grep '^>')"
touch -d '-35 minutes' "$STATE/status/watchdog.md"   # 20m -> 35m ago: both <1h, still stale
"$ST" --skip machines,agents --quiet --publish > "$OUT" 2>&1
[[ $(mt) == "$m0" ]] && ok "an age ticking inside its bucket: left alone" || bad "age tick rewrote STATUS.md"
ls "$DOCS" "$DOCS/STATUS" "$STATE/status" | grep -q '\.tmp' && bad "temp file left after a no-change publish" || ok "no temp file after a no-change publish"
# one source changes: only its copy is rewritten
printf '2026-11-05T12:00:00Z act new finding\n' >> "$STATE/status/watchdog.log"
wm0=$(stat -c %Y "$DOCS/STATUS/watchdog.md")
"$ST" --skip machines,agents --quiet --publish > "$OUT" 2>&1
[[ $(stat -c %Y "$DOCS/STATUS/watchdog.md") != "$wm0" ]] && ok "new watchdog log line: its copy rewritten" || bad "watchdog copy not rewritten"
has  "new log line in the copy"  "act new finding" "$DOCS/STATUS/watchdog.md"
[[ $(mts | grep -v watchdog) == "$(echo "$ms0" | grep -v watchdog)" ]] && ok "the other copies left alone" || bad "other copies rewritten"
printf 'delta\tready\t2026-11-05T10:00:00Z\tcoder-2\tclaude/delta\t\tnew one\t2026-11-05T09:00:00Z\n' >> "$STATE/board/items.tsv"
"$ST" --skip machines,agents --quiet --publish > "$OUT" 2>&1
[[ $(mt) != "$m0" ]] && ok "new item: STATUS.md rewritten" || bad "new item did not rewrite STATUS.md"
has  "new item on the page"      "| ready | delta |" "$P"
touch -d '-1 hour' "$P"; m0=$(mt)
mv "$S/locks.sh" "$T/locks.sh.keep"
printf '#!/usr/bin/env bash\nprintf "%%-32s %%s\\n" heavy.lock "held: pid 42 since 2026-11-05 10:00:00: client-test" merge.lock "held: pid 77 since 2026-11-05 10:02:00: squash-merge" postmerge.lock free\n' > "$S/locks.sh"; chmod +x "$S/locks.sh"
"$ST" --skip machines,agents --quiet --publish > "$OUT" 2>&1
[[ $(mt) != "$m0" ]] && ok "lock taken: STATUS.md rewritten" || bad "a newly held lock did not rewrite STATUS.md"
has  "held lock on the page"     "pid 77" "$P"
mv "$T/locks.sh.keep" "$S/locks.sh"
# a stray #word becomes code, a #word inside backticks and a heading stay
cp "$STATE/status/needs-user.md" "$T/nu.keep"
printf '%s\n' '# Needs the user' '' 'ask about #tagged thing and `#kept2`' > "$STATE/status/needs-user.md"
"$ST" --skip machines,agents --quiet --publish --no-refresh > "$OUT" 2>&1
has  "stray #word backticked"    'ask about `#tagged` thing' "$P"
has  "#word in code left alone"  '`#kept2`' "$P"
hasnt "no double backticks"      '``#kept2' "$P"
cp "$T/nu.keep" "$STATE/status/needs-user.md"
unset FB_STATUS_PAGE_DIR
"$ST" --print-units | grep -q 'ExecStart=.*/status.sh --quiet --publish' && ok "timer unit runs --publish" || bad "unit lacks --publish"
"$ST" --print-units | grep -q 'OnUnitActiveSec=5min' && ok "timer every 5 min by default" || bad "timer not every 5 min"
"$ST" --every 15 --print-units | grep -q 'OnUnitActiveSec=15min' && ok "--every 15 sets the interval" || bad "--every ignored"

"$ST" --skip machines,agents --quiet > "$OUT" 2>&1; rc=$?
[[ $rc == 0 && $(cat "$OUT") == "$B" ]] && ok "--quiet prints the path" || bad "--quiet: rc $rc, $(cat "$OUT")"
hasnt "--skip machines" "# Machines" "$B"
hasnt "--skip agents"   "# Agents" "$B"
"$ST" --skip bogus > "$OUT" 2>&1; [[ $? == 2 ]] && ok "bad --skip exits 2" || bad "bad --skip did not exit 2"
FB_STATUS_TIMEOUT=x "$ST" > "$OUT" 2>&1; [[ $? == 2 ]] && ok "bad FB_STATUS_TIMEOUT exits 2" || bad "bad timeout accepted"

# no board, no needs-user page, no transcripts
rm -rf "$STATE/board" "$STATE/status/needs-user.md"; rm -rf "$TR"; mkdir -p "$TR"
"$ST" --skip machines > "$OUT" 2>&1; rc=$?
[[ $rc == 0 ]] && ok "empty state still exits 0" || bad "empty state exit $rc"
has "no board degrades"    "unavailable: no board" "$B"
has "no needs-user page"   "unavailable: no \`.claude/status/needs-user.md\`" "$B"
has "no agents"            "None running in the last 2 h" "$B"

# --- smoke run with the real helper scripts on an empty temp state (no worker probes) ---------------
R="$T/real"; mkdir -p "$R"
unset FB_STATUS_SCRIPTS FB_TRANSCRIPTS
FB_STATE_DIR="$R" FB_STATUS_TIMEOUT=60 FB_TRANSCRIPTS="$T/none" "$ST" --skip machines > "$OUT" 2>&1; rc=$?
[[ $rc == 0 ]] && ok "real helpers: exit 0" || { bad "real helpers: exit $rc"; sed 's/^/     | /' "$OUT" | head -n 40; }
for h in "# Needs the user" "# Items" "# Locks" "# Post-merge" "# Recent tests"; do has "real helpers: $h" "$h" "$R/status/board.md"; done
hasnt "real helpers: nothing timed out" "took over" "$R/status/board.md"

(( fail )) && { echo "status-selftest: FAILED"; exit 1; }
echo "status-selftest: all passed"
