import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import type { Ir, Vec3 } from './ir';
import { parseIr } from './ir';
import { irToVoxels } from './voxels';

const box = (min: Vec3, size: Vec3, role: string) => ({ min, size, role });
const ir = (boxes: Ir['boxes']): Ir => ({ irVersion: 0, size: [5, 5, 5], boxes });

describe('irToVoxels', () => {
  it('expands a box to size.x*y*z voxels', () => {
    const v = irToVoxels(ir([box([0, 0, 0], [5, 5, 5], 'wall')]));
    expect(v).toHaveLength(125);
    expect(v.every((c) => c.role === 'wall')).toBe(true);
  });

  it('is empty for no boxes', () => {
    expect(irToVoxels(ir([]))).toEqual([]);
  });

  it('later boxes override overlapping cells, output is ordered and deterministic', () => {
    const i = ir([box([0, 0, 0], [2, 1, 1], 'wall'), box([1, 0, 0], [2, 1, 1], 'roof')]);
    const v = irToVoxels(i);
    expect(v.map((c) => `${c.x}:${c.role}`)).toEqual(['0:wall', '1:roof', '2:roof']);
    expect(irToVoxels(i)).toEqual(v);
  });
});

describe('CLI fixture fixtures/box5.json (generated by `fractal-cli gen`)', () => {
  const parsed = parseIr(JSON.parse(readFileSync(new URL('../fixtures/box5.json', import.meta.url), 'utf8')));

  it('parses and is a 5x5x5 box', () => {
    expect(parsed.size).toEqual([5, 5, 5]);
    const v = irToVoxels(parsed);
    expect(v).toHaveLength(125);
    expect(v.every((c) => c.x < 5 && c.y < 5 && c.z < 5)).toBe(true);
  });

  it('has at least two material roles', () => {
    const roles = new Set(irToVoxels(parsed).map((c) => c.role));
    expect(roles.size).toBeGreaterThanOrEqual(2);
  });
});

describe('parseIr', () => {
  it('rejects wrong version and malformed boxes', () => {
    expect(() => parseIr({ irVersion: 1, size: [1, 1, 1], boxes: [] })).toThrow(/irVersion/);
    expect(() => parseIr({ irVersion: 0, size: [1, 1, 1], boxes: [{ min: [0, 0], size: [1, 1, 1], role: 'a' }] })).toThrow(/min/);
    expect(() => parseIr({ irVersion: 0, size: [1, 1, 1] })).toThrow(/boxes/);
    expect(() => parseIr(null)).toThrow();
  });
});
